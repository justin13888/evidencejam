"""Item 15: sample answered texts from renderer `faithful` for an overclaim review.

Population: every cause x outcome class pair of the real taxonomy that yields an answered verdict, under
two engines: the current defaults (`baseline` interpreter/aggregator/grader/citer) and the item 6/11/13
engine (`sentence`/`studies`/`rubric`/`precise`, as in tests/strategies/test_traps.py). The linker is
bypassed (frames name the classes, labels as the question spans). Items with more than MAX_CITED cited
edges are left out so a reviewer can read every sentence; that bias is stated in the output.

Sampling: seeded, stratified by (direction, all-associational?). Strata are visited round-robin in a
fixed order, one item at a time, until N items; duplicate texts are skipped.

Writes the item section of experiments/renderer/review_20.md between the ITEMS markers (verdict lines
recorded by the reviewer live outside the markers and are preserved). 0 LLM calls.

    python experiments/renderer/review_sample.py [--seed 15] [--n 20]
"""

from __future__ import annotations

import argparse
import random
import re
from collections import defaultdict
from pathlib import Path

from camoreasoning import registry
from camoreasoning.config import CACHE_DIR, Settings
from camoreasoning.contracts import Frame, ParsedQuestion, Question, Ref, Side
from camoreasoning.pipeline import make_context
from camoreasoning.strategies.grader.rubric import is_associational
from camoreasoning.strategies.renderer.faithful import cite_labels

OUT = Path(__file__).parent / "review_20.md"
MAX_CITED = 12
ENGINES = {
    "default": {"interpreter": "baseline", "aggregator": "baseline", "grader": "baseline", "citer": "baseline"},
    "B": {"interpreter": "sentence", "aggregator": "studies", "grader": "rubric", "citer": "precise"},
}
DIRECTIONS = ("increase", "decrease", "no_effect", "mixed", "unclear")
BEGIN, END = "<!-- ITEMS:BEGIN (generated by review_sample.py) -->", "<!-- ITEMS:END -->"


def population(ctx):
    tax = ctx.taxonomy
    retr, renderer = registry.get("retriever", "baseline"), registry.get("renderer", "faithful")
    causes = [c for c in tax.classes.values() if c.kind in ("cause", "both")]
    outcomes = [c for c in tax.classes.values() if c.kind in ("outcome", "both")]
    items = []
    for engine, names in ENGINES.items():
        s = {st: registry.get(st, n) for st, n in names.items()}
        for c in causes:
            for o in outcomes:
                if c.id == o.id:
                    continue
                cause, outcome = c.label.lower(), o.label.lower()
                q = Question(f"{c.id}->{o.id}", f"What effect does {cause} have on {outcome}?")
                frame = Frame(ParsedQuestion(q, cause, outcome, True), Side(cause, (Ref(c.id),)),
                              Side(outcome, (Ref(o.id),)), "regex", 1.0)  # fmt: skip
                cands = retr.retrieve(frame, ctx)
                if not cands.forward:
                    continue
                verdict = s["aggregator"].aggregate(s["interpreter"].interpret(cands, ctx), cands, ctx)
                if verdict.status != "answered":
                    continue
                certainty = s["grader"].grade(verdict, ctx)
                cited = s["citer"].cite(verdict, ctx)
                text, _ = renderer.render(verdict, cands, certainty, ctx)
                assoc = all(is_associational(v, ctx) for v in verdict.included)
                items.append({"engine": engine, "q": q, "verdict": verdict, "certainty": certainty,
                              "cited": cited, "text": text, "assoc": assoc})  # fmt: skip
    return items


def sample(items, n: int, seed: int):
    strata = defaultdict(list)
    for it in items:
        if len(it["cited"]) <= MAX_CITED:
            strata[(it["verdict"].direction, it["assoc"])].append(it)
    rng = random.Random(seed)
    for k in sorted(strata):
        rng.shuffle(strata[k])
    order = [(d, a) for a in (False, True) for d in DIRECTIONS if (d, a) in strata]
    picked, seen = [], set()
    while len(picked) < n and any(strata[k] for k in order):
        for k in order:
            while strata[k]:
                it = strata[k].pop()
                if it["text"] not in seen:
                    seen.add(it["text"])
                    picked.append(it)
                    break
            if len(picked) == n:
                break
    return picked, {k: len(v) for k, v in strata.items()}


def node_name(ctx, nid: str) -> str:
    n = ctx.graph.nodes.get(nid, {})
    qual = n.get("state_or_change_qualifier")
    name = n.get("name") or nid
    return f"[{qual}] {name}" if qual else name


def render_item(i: int, it, ctx) -> str:
    v = it["verdict"]
    labels = cite_labels([d for d, _ in v.doc_effects] + [ctx.graph.edges[e]["source_document"] for e in it["cited"]],
                         ctx)  # fmt: skip
    lines = [f"### R{i:02d}  `{it['q'].id}`  (engine {it['engine']})", "",
             f"Question: {it['q'].text}", "",
             f"Pipeline fields: direction `{v.direction}`, certainty `{it['certainty']}`, "
             f"{len(v.doc_effects)} studies counted, {len(it['cited'])} cited edges.", "",
             f"> {it['text']}", "", "Cited edges (grouped by study):", ""]  # fmt: skip
    by_doc = defaultdict(list)
    for e in it["cited"]:
        by_doc[ctx.graph.edges[e]["source_document"]].append(e)
    for d in sorted(by_doc, key=lambda d: labels.get(d, d)):
        lines.append(f"- **{labels.get(d, d)}** (`{d}`)")
        for e in by_doc[d]:
            edge = ctx.graph.edges[e]
            sent = re.sub(r"\s+", " ", edge.get("original_sentence") or "").strip()
            neg = " (negated)" if edge.get("negated") else ""
            lines.append(f"  - `{e}` {node_name(ctx, edge['subject'])} **{edge['predicate']}{neg}** "
                         f"{node_name(ctx, edge['object'])}: \"{sent}\"")  # fmt: skip
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=15)
    ap.add_argument("--n", type=int, default=20)
    args = ap.parse_args()
    ctx = make_context(Settings(), out_dir=CACHE_DIR / "renderer_review")
    items = population(ctx)
    picked, sizes = sample(items, args.n, args.seed)
    strata = ", ".join(f"{d}/{'assoc' if a else 'causal'}={n}" for (d, a), n in sorted(sizes.items()))
    body = [BEGIN, "",
            f"Seed {args.seed}; population {len(items)} answered (engine, pair) results; items with more than "
            f"{MAX_CITED} cited edges excluded. Stratum sizes before sampling: {strata}.", ""]  # fmt: skip
    body += [render_item(i + 1, it, ctx) + "\n" for i, it in enumerate(picked)]
    body.append(END)
    block = "\n".join(body)
    old = OUT.read_text(encoding="utf-8") if OUT.exists() else f"# Renderer review\n\n{BEGIN}\n{END}\n"
    pre, _, rest = old.partition(BEGIN)
    _, _, post = rest.partition(END)
    OUT.write_text(pre + block + post, encoding="utf-8")
    print(f"wrote {len(picked)} items to {OUT}")


if __name__ == "__main__":
    main()
